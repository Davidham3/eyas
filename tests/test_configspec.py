# kind gating: a patch the task kind does not implement is never applied


def test_task_patches_are_kind_gated(spec) -> None:
    mcq_opro = cell_config(spec, "pets", "opro")
    assert mcq_opro["task"]["params"]["instruction_pos"] == "Q_begin"
    math_opro = cell_config(spec, "gsm8k", "opro")
    assert "instruction_pos" not in math_opro["task"]["params"]

    mcq_cot = cell_config(spec, "pets", "cot")
    assert mcq_cot["task"]["params"]["assistant_prefix"] == "Let's think step by step."
    for ds in ("sroie", "textvqa"):
        assert "assistant_prefix" not in cell_config(spec, ds, "cot")["task"]["params"]

    assert cell_config(spec, "pets", "spo")["task"]["params"]["raw_template"] is True
    assert cell_config(spec, "gsm8k", "spo")["task"]["params"]["raw_template"] is True
    assert "raw_template" not in cell_config(spec, "textvqa", "spo")["task"]["params"]


def test_judge_follows_method_family_and_board_kind(spec) -> None:
    assert cell_config(spec, "pets", "opro")["judge"] == {
        "name": "mcq_llm",
        "params": {"variant": "opro", "classify_original_task": True},
    }
    assert cell_config(spec, "cub", "cot")["judge"]["params"]["variant"] == "cot"
    assert cell_config(spec, "pets", "protegi")["judge"]["params"] == {"variant": "default"}
    # rule-scored boards never carry a judge, whatever the method
    for method in sorted(METHODS):
        for ds in ("sroie", "textvqa", "gsm8k"):
            assert "judge" not in cell_config(spec, ds, method), f"{ds}/{method}"


def test_prompts_and_bandit_quota_layers_compose(spec) -> None:
    # dataset prompt asset lands on the method strategy without swallowing it
    spo = cell_config(spec, "gsm8k", "spo")["strategy"]
    assert spo["params"] == {"rounds": 20, "prompt_includes_choices": False}
    assert len(spo["seeds"]) == 2
