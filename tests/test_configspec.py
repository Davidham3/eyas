"""Config-spec assembler contract tests (zero GPU, zero network).

Main evidence: golden parity through digest manifests. The committed goldens
(``tests/goldens/configspec/``) are a *derived snapshot*: two sha256 manifests
— one ``<digest>  <id>`` line per shipped quickstart cell (sorted by cell id)
and one per benchmark-matrix cell (in expansion order, because the axis
declaration order is the backend-sharing contract) — plus the full readable
JSON of a few representative cells, one per distinct assembly branch. Nothing
here trusts the snapshot: every parity test recomputes the digests from
``configs/spec`` through the assembler itself and compares whole tables
against the committed lines. Regeneration is never implicit — when the spec
changes on purpose, ``uv run python scripts/gen_configspec_goldens.py --regen``
rewrites the manifests and the regenerated diff is what a human reviews. The
goldens stay after the per-cell YAMLs are deleted: they are test assets, never
runtime inputs.

Plus: fail-fast spec validation (unknown keys / dangling references / retired
matrix features) and the kind-gating behaviour the patches promise.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

import pytest
from _spec_cells import cell_id, shipped_cells

from eyas.configspec import benchmark_cells, cell_config, cell_digest, load_spec
from eyas.engine.runtime import load_config

_ROOT = Path(__file__).resolve().parents[1]
_GOLDEN = _ROOT / "tests" / "goldens" / "configspec"
SPEC_DIR = _ROOT / "configs" / "spec"

DATASETS = {"gsm8k", "pets", "sroie", "cub", "textvqa", "nextqa", "mixed"}
METHODS = {"raw", "cot", "hill_climb", "evoprompt", "opro", "ape", "protegi", "spo"}

#: representative cells kept as full readable JSON (one per assembly branch);
#: the same list scripts/gen_configspec_goldens.py regenerates
FEATURE_CELLS = (
    "gsm8k_cot",
    "cub_raw",
    "pets_protegi",
    "textvqa_ape",
    "mixed_cot",
    "pets_raw_openai",
)

#: every manifest opens with these two lines verbatim; regen stamps them, a
#: hand edit breaks them
_MANIFEST_HEADER = (
    "# GENERATED by scripts/gen_configspec_goldens.py --regen — do not edit.\n"
    "# Verify: uv run python scripts/gen_configspec_goldens.py\n"
)

# sha256sum convention: <hex digest><two spaces><id>. The digest width is
# derived from cell_digest itself, never hard-coded.
_DATA_LINE = re.compile(rf"^[0-9a-f]{{{len(cell_digest({}))}}}  [^ ]+$")


def _parse_cell_file(stem: str) -> tuple[str, str, str | None]:
    parts = stem.split("_")
    ds, parts = parts[0], parts[1:]
    assert ds in DATASETS, stem
    variant = None
    if parts[-1] == "openai":
        variant, parts = "openai", parts[:-1]
    method = "_".join(parts)
    assert method in METHODS, stem
    return ds, method, variant


def _manifest_rows(name: str) -> list[tuple[str, str]]:
    """The ``(digest, id)`` pairs of one manifest's data lines, in file order."""
    lines = (_GOLDEN / name).read_text(encoding="utf-8").splitlines()
    return [tuple(line.split("  ", 1)) for line in lines if line and not line.startswith("#")]


@pytest.fixture(scope="module")
def spec():
    return load_spec(SPEC_DIR)


def test_quickstart_manifest_matches_assembly(spec) -> None:
    rows = [(cell_digest(cell_config(spec, *c)), cell_id(*c)) for c in shipped_cells()]
    rows.sort(key=lambda row: row[1])  # the manifest is keyed and sorted by cell id
    assert _manifest_rows("quickstart.sha256") == rows


def test_benchmark_manifest_matches_expansion(spec) -> None:
    rows = [(cell_digest(cfg), name) for name, cfg in benchmark_cells(spec)]
    # order-sensitive on purpose: expansion order is the backend-sharing contract
    assert _manifest_rows("benchmark.sha256") == rows


def test_manifest_lines_are_canonical() -> None:
    header = _MANIFEST_HEADER.splitlines()
    for name in ("quickstart.sha256", "benchmark.sha256"):
        lines = (_GOLDEN / name).read_text(encoding="utf-8").splitlines()
        assert lines[:2] == header, f"{name}: header edited by hand"
        assert all(_DATA_LINE.match(line) for line in lines[2:] if line), f"{name}: malformed line"


def test_quickstart_manifest_covers_shipped_surface() -> None:
    ids = {cid for _, cid in _manifest_rows("quickstart.sha256")}
    assert ids == {cell_id(*c) for c in shipped_cells()}


@pytest.mark.parametrize("stem", FEATURE_CELLS)
def test_feature_cells_full_equality(spec, stem: str) -> None:
    dataset, method, variant = _parse_cell_file(stem)
    assembled = cell_config(spec, dataset, method, variant)
    expected = json.loads((_GOLDEN / "cells" / f"{stem}.json").read_text(encoding="utf-8"))
    assert assembled == expected, f"feature cell {stem} drifted from the assembly"


def test_assembled_cells_pass_the_runtime_validator(spec, tmp_path) -> None:
    # the strict loader (required sections + plugin imports) accepts every cell
    import yaml

    for dataset in sorted(DATASETS):
        for method in sorted(METHODS):
            cfg = cell_config(spec, dataset, method)
            path = tmp_path / f"{dataset}_{method}.yaml"
            path.write_text(yaml.safe_dump(cfg), encoding="utf-8")
            assert load_config(path)["strategy"]["name"] == method


