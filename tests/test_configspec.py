# fail-fast contract


def _write_spec(tmp_path: Path, mutate) -> Path:
    import yaml

    dst = tmp_path / "spec"
    dst.mkdir(parents=True)
    for f in SPEC_DIR.glob("*.yaml"):
        payload = yaml.safe_load(f.read_text(encoding="utf-8"))
        mutate(f.name, payload)
        (dst / f.name).write_text(yaml.safe_dump(payload, sort_keys=False), encoding="utf-8")
    return dst


def test_unknown_keys_and_dangling_references_fail_fast(tmp_path) -> None:
    def bad_key(name, payload):
        if name == "datasets.yaml":
            payload["datasets"]["pets"]["temperature"] = 3

    with pytest.raises(ValueError, match="unknown keys.*temperature"):
        load_spec(_write_spec(tmp_path / "a", bad_key))

    def dangling_cell(name, payload):
        if name == "cells.yaml":
            payload["cells"]["nope/raw"] = {"set": {"run.seed": 1}}

    with pytest.raises(ValueError, match="unknown dataset"):
        load_spec(_write_spec(tmp_path / "b", dangling_cell))

    def dangling_variant(name, payload):
        if name == "cells.yaml":
            payload["variants"]["openai"]["overrides"]["gsm8k/raw"] = {
                "set": {"backend.params.model": "x"}
            }

    with pytest.raises(ValueError, match="not in variants.openai.available"):
        load_spec(_write_spec(tmp_path / "c", dangling_variant))


def test_benchmark_base_features_are_retired(tmp_path) -> None:
    def rebase(name, payload):
        if name == "benchmark.yaml":
            payload["base"] = "configs/quickstart_{dataset}_{method}.yaml"

    with pytest.raises(ValueError, match="must not carry a base"):
        load_spec(_write_spec(tmp_path / "a", rebase))

    def combo_base(name, payload):
        if name == "benchmark.yaml":
            payload["combos"].append(
                {"when": {"dataset": "pets"}, "base": "x.yaml", "set": {"run.seed": 1}}
            )

    with pytest.raises(ValueError, match="base re-basing is retired"):
        load_spec(_write_spec(tmp_path / "b", combo_base))


def test_unavailable_variant_cell_fails_at_assembly(spec) -> None:
    with pytest.raises(ValueError, match="no 'openai' variant"):
        cell_config(spec, "gsm8k", "spo", variant="openai")
    with pytest.raises(ValueError, match="unknown method"):
        cell_config(spec, "pets", "no_such_method")
    with pytest.raises(ValueError, match="unknown dataset"):
        cell_config(spec, "no_such_dataset", "raw")


def test_cell_digest_known_value() -> None:
    """The canonical serialization is pinned by a known value: sorted keys
    (insertion order never enters), compact separators, ``ensure_ascii=False``
    escaping — the digests the golden manifests key on must not drift across
    platforms or Python versions."""
    assert cell_digest({"b": 1, "a": [1.5, True, None, "快照"]}) == (
        "fb72008cd58e05fffb5bf663058de966cfd1ef203200f414745163c5de6e13a9"
    )
