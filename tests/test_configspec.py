    assert evo["params"] == {"mode": "ga", "popsize": 10, "rounds": 3}
    assert len(evo["seeds"]) == 10
    # protegi switches the budget section; cells.yaml pins the toy-split quota
    bandit = cell_config(spec, "pets", "protegi")["budget"]
    assert bandit["name"] == "bandit"
    assert bandit["params"] == {
        "eval_rounds": 8,
        "c": 2.0,
        "keep_top": 0.5,
        "samples_per_eval": 9,
    }
    assert cell_config(spec, "pets", "raw")["budget"]["name"] == "flat"


