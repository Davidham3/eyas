# ------------------------------------------------------------------ method cards


def _qs_pair(tmp_path: Path) -> None:
    """Two methods x two seeds on the quickstart stem (textvqa)."""
    final_cost = {"requests": 100, "judge_requests": 0}
    _cell(tmp_path, "qs", "textvqa", "raw", "42", 0.80, final_cost=final_cost)
    _cell(tmp_path, "qs", "textvqa", "raw", "43", 0.84, final_cost=final_cost)
    # cot: loop bills 600 reqs / 40 judge on seed 42 (the card's cost row reads seed 42)
    _cell(tmp_path, "qs", "textvqa", "cot", "42", 0.90, loop_requests=600, final_cost=final_cost)
    _cell(tmp_path, "qs", "textvqa", "cot", "43", 0.86, final_cost=final_cost)


def test_method_cards_emit_evidence_lines(tmp_path: Path, capsys) -> None:
    """One evidence line per method: mean ± population σ (n=seeds), Δ vs raw in pp, cost."""
    mod = _load()
    _qs_pair(tmp_path)

    rc = mod.main(["--outputs-root", str(tmp_path), "method-cards", "--dataset", "textvqa"])

    assert rc == 0
    out = capsys.readouterr().out
    # hand-computed means: raw (0.80+0.84)/2 = 82.0, pstdev 0.02 -> ±2.0; cot mean 88.0 ±2.0
    assert "`raw`" in out
    assert "82.0% ±2.0% (n=2)" in out
    assert "`cot`" in out
    assert "88.0% ±2.0% (n=2)" in out
    # Δ vs raw for the non-raw row only: (0.88 - 0.82) * 100 = +6.0 pp
    assert "Δ +6.0 pp vs raw" in out
    cot_line = next(line for line in out.splitlines() if "`cot`" in line)
    assert "Δ" not in next(line for line in out.splitlines() if "`raw`" in line)
    # cost summary: loop requests + judge requests (seed 42) and the test pass
    assert "req 600 (judge 0)" in cot_line
    assert "test pass req 100" in cot_line


def test_method_cards_numbers_match_quickstart_effect(tmp_path: Path, capsys) -> None:
    """Drift discipline: the card lines and the §3 table are the same aggregation."""
    mod = _load()
    _qs_pair(tmp_path)
    # the §3 generator wants full coverage; the remaining six methods land at 0.50
    six_cost = {"requests": 100, "judge_requests": 0}
    for method in ("evoprompt", "hill_climb", "opro", "protegi", "spo", "ape"):
        _cell(tmp_path, "qs", "textvqa", method, "42", 0.50, final_cost=six_cost)
        _cell(tmp_path, "qs", "textvqa", method, "43", 0.50, final_cost=six_cost)

    mod.main(["--outputs-root", str(tmp_path), "method-cards", "--dataset", "textvqa"])
    cards = capsys.readouterr().out
    mod.main(["--outputs-root", str(tmp_path), "quickstart-effect", "--dataset", "textvqa"])
    effect = capsys.readouterr().out

    # the §3 table publishes 0.820 ± 0.020 / 0.880 ± 0.020 and Δ +6.0 — the cards
    # must carry the identical facts in percent form
    assert "0.820 ± 0.020" in effect and "82.0% ±2.0%" in cards
    assert "0.880 ± 0.020" in effect and "88.0% ±2.0%" in cards
    assert "+6.0" in effect and "Δ +6.0 pp vs raw" in cards
    assert "0.500 ± 0.000" in effect and cards.count("50.0% ±0.0% (n=2)") == 6


