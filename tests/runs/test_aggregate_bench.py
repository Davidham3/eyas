def test_bench_effect_reports_parsed_only_when_parse_fail_is_material(
    tmp_path: Path, capsys
) -> None:
    """A cell whose parse-fail rate is material carries the parsed-only figure.

    Protocol accuracy counts unparseable predictions as wrong, so a 20% parse
    fail on 60% accuracy is 75% accuracy over the answers that parsed.
    """
    mod = _load()
    _cell(tmp_path, "matrix_q4b", "nextqa", "raw", "42", 0.60, extra={"parse_fail": 0.20})

    rc = mod.main(["--outputs-root", str(tmp_path), "bench-effect", "--dataset", "nextqa"])

    assert rc == 0
    out = capsys.readouterr().out
    assert "60.0% (n=1)<br>pf 20.0% → parsed 75.0%" in out


def test_bench_effect_parsed_only_averages_parsed_accuracy_per_seed(tmp_path: Path, capsys) -> None:
    """Parsed accuracy is computed per seed, then averaged across seeds.

    seed 42: 0.60 / (1 - 0.20) = 0.75; seed 43: 0.50 / (1 - 0.00) = 0.50.
    Mean parsed = 62.5%, not mean_accuracy / (1 - mean_pf) = 61.1%.
    """
    mod = _load()
    _cell(tmp_path, "matrix_q4b", "nextqa", "raw", "42", 0.60, extra={"parse_fail": 0.20})
    _cell(tmp_path, "matrix_q4b", "nextqa", "raw", "43", 0.50, extra={"parse_fail": 0.00})

    rc = mod.main(["--outputs-root", str(tmp_path), "bench-effect", "--dataset", "nextqa"])

    assert rc == 0
    out = capsys.readouterr().out
    assert "55.0% ±5.0% (n=2)<br>pf 10.0% → parsed 62.5%" in out


