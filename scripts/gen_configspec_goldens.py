#!/usr/bin/env python3
"""Generate (and verify) the config-spec golden hash manifests.

why: the assembled cell content is what the goldens must pin — not the
rendering of a cell. A sha256 over the canonical serialization (``cell_digest``)
detects any semantic change to a cell while staying immune to cosmetic
reformatting, so the snapshot corpus collapses to two hash manifests plus a
handful of deliberately readable representative cells.

what: re-derives, from ``configs/spec``,

  * ``tests/goldens/configspec/quickstart.sha256`` — one ``<digest>  <cell_id>``
    line per shipped quickstart cell (the ``shipped_cells()`` surface), sorted
    by cell id;
  * ``tests/goldens/configspec/benchmark.sha256`` — one ``<digest>  <run_name>``
    line per benchmark-matrix cell, in expansion order (the axis declaration
    order is the backend-sharing contract, so the order itself is pinned);
  * ``tests/goldens/configspec/cells/<id>.json`` — full readable JSON for the
    representative cells listed in ``READABLE_CELLS``.

Both manifests open with the two ``# `` header lines below and then only data
lines of the sha256sum convention ``^[0-9a-f]{64}  <id>$`` (two spaces). No
timestamps anywhere: two ``--regen`` runs are byte-identical.

Default mode only checks: recompute both manifests, compare against the
committed files line by line, print drift as ``+id`` (missing), ``-id``
(unexpected) and ``M id`` (digest mismatch) lines, and exit 0 on a match or
1 on any drift (including missing files). It never writes.

``--regen`` rewrites the manifests and the representative cells.

Usage (repo root):
    uv run python scripts/gen_configspec_goldens.py          # check
    uv run python scripts/gen_configspec_goldens.py --regen  # rewrite
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
# The repo root goes on sys.path for tests._spec_cells; eyas itself resolves
# from the sync'd/installed environment (uv run / pip install), never from here.
sys.path.insert(0, str(REPO))

from eyas.configspec import benchmark_cells, cell_digest  # noqa: E402
from tests._spec_cells import cell, cell_id, shipped_cells, spec  # noqa: E402

GOLDEN_DIR = REPO / "tests" / "goldens" / "configspec"
_MANIFEST_HEADER = (
    "# GENERATED by scripts/gen_configspec_goldens.py --regen — do not edit.\n"
    "# Verify: uv run python scripts/gen_configspec_goldens.py\n"
)

#: cells whose full assembled JSON stays committed as readable goldens
READABLE_CELLS = (
    "gsm8k_cot",
    "cub_raw",
    "pets_protegi",
    "textvqa_ape",
    "mixed_cot",
    "pets_raw_openai",
)


def _manifest_lines() -> dict[str, list[str]]:
    """``{manifest filename: data lines}`` recomputed from the spec."""
    quickstart = sorted((cell_id(*c), cell_digest(cell(*c))) for c in shipped_cells())
    benchmark = [(name, cell_digest(cfg)) for name, cfg in benchmark_cells(spec())]
    return {
        "quickstart.sha256": [f"{digest}  {cid}" for cid, digest in quickstart],
        "benchmark.sha256": [f"{digest}  {run_name}" for run_name, digest in benchmark],
    }


def _manifest_text(lines: list[str]) -> str:
    return _MANIFEST_HEADER + "".join(f"{line}\n" for line in lines)


def _check_manifest(path: Path, expected: list[str]) -> bool:
    """Compare one committed manifest against the recomputed lines; report drift."""
    rel = path.relative_to(REPO)
    if not path.is_file():
        print(f"{rel}: missing (run --regen)")
        return False
    actual = path.read_text(encoding="utf-8")
    if actual == _manifest_text(expected):
        print(f"{rel}: ok ({len(expected)} cells)")
        return True

    def parse(text: str) -> dict[str, str]:
        return dict(
            (line.split("  ", 1)[1], line.split("  ", 1)[0])
            for line in text.splitlines()
            if line and not line.startswith("# ") and "  " in line
        )

    actual_map = parse(actual)
    malformed = sum(
        1 for line in actual.splitlines() if line and not line.startswith("# ") and "  " not in line
    )
    if malformed:
        print(f"{rel}: {malformed} malformed data line(s)")
    expected_map = dict(line.split("  ", 1)[::-1] for line in expected)
    for cid, digest in expected_map.items():
        if cid not in actual_map:
            print(f"{rel}: +{cid}")
        elif actual_map[cid] != digest:
            print(f"{rel}: M {cid}")
    for cid in actual_map:
        if cid not in expected_map:
            print(f"{rel}: -{cid}")
    if set(actual_map) == set(expected_map):
        # same cells and digests, but the bytes differ: header, order or line endings
        print(f"{rel}: layout drift (id order, header or line endings)")
    return False


def _regen() -> int:
    lines = _manifest_lines()
    for name, data_lines in lines.items():
        path = GOLDEN_DIR / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(_manifest_text(data_lines), encoding="utf-8", newline="\n")
        print(f"wrote {path.relative_to(REPO)} ({len(data_lines)} cells)")

    cells_dir = GOLDEN_DIR / "cells"
    cells_dir.mkdir(parents=True, exist_ok=True)
    by_id = {cell_id(*c): c for c in shipped_cells()}
    missing = [cid for cid in READABLE_CELLS if cid not in by_id]
    if missing:
        raise RuntimeError(f"representative cells not in the shipped surface: {missing}")
    for cid in READABLE_CELLS:
        payload = json.dumps(cell(*by_id[cid]), sort_keys=True, indent=2, ensure_ascii=False) + "\n"
        path = cells_dir / f"{cid}.json"
        path.write_text(payload, encoding="utf-8", newline="\n")
        print(f"wrote {path.relative_to(REPO)}")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--regen", action="store_true", help="rewrite the manifests and representative cells"
    )
    args = parser.parse_args(argv)
    if args.regen:
        return _regen()
    lines = _manifest_lines()
    ok = all([_check_manifest(GOLDEN_DIR / name, data_lines) for name, data_lines in lines.items()])
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
